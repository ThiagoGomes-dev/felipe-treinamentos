-- Configurações gerais do site (nome, frase e cor). Só existe uma linha.
CREATE TABLE site (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(120)  NOT NULL,
    slogan          VARCHAR(200),
    cor_destaque    VARCHAR(20)   NOT NULL DEFAULT '#e3161b'
);

-- Arquivos enviados pelo painel (imagens e vídeos), guardados no disco do servidor.
CREATE TABLE arquivo (
    id              VARCHAR(36)   PRIMARY KEY,
    nome_original   VARCHAR(300)  NOT NULL,
    content_type    VARCHAR(120)  NOT NULL,
    tamanho         BIGINT        NOT NULL,
    caminho         VARCHAR(500)  NOT NULL,
    criado_em       TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Curso (produto vendido). O aluno só vê o conteúdo dos cursos liberados para ele.
CREATE TABLE curso (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug              VARCHAR(120)  NOT NULL UNIQUE,
    titulo            VARCHAR(160)  NOT NULL,
    subtitulo         VARCHAR(200),
    descricao         VARCHAR(2000),
    capa_id           VARCHAR(36),
    eduzz_produto_id  VARCHAR(60),
    link_venda        VARCHAR(1000),
    ordem             INT           NOT NULL DEFAULT 0,
    publicado         BOOLEAN       NOT NULL DEFAULT TRUE
);

-- Módulo: cada card dentro do curso (um tipo de exercício, ex.: "Joelho forte").
CREATE TABLE modulo (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    curso_id    BIGINT        NOT NULL REFERENCES curso (id) ON DELETE CASCADE,
    slug        VARCHAR(120)  NOT NULL,
    titulo      VARCHAR(120)  NOT NULL,
    descricao   VARCHAR(1000),
    capa_id     VARCHAR(36),
    ordem       INT           NOT NULL DEFAULT 0,
    publicado   BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_modulo_slug UNIQUE (curso_id, slug)
);

-- Tópico: subtópico dentro do módulo (título + descrição leve + vídeos).
CREATE TABLE topico (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    modulo_id   BIGINT        NOT NULL REFERENCES modulo (id) ON DELETE CASCADE,
    titulo      VARCHAR(160)  NOT NULL,
    descricao   VARCHAR(2000),
    ordem       INT           NOT NULL DEFAULT 0
);

-- Vídeo: arquivo enviado ao servidor (arquivo_id) ou link externo (url).
CREATE TABLE video (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topico_id   BIGINT        NOT NULL REFERENCES topico (id) ON DELETE CASCADE,
    titulo      VARCHAR(160)  NOT NULL,
    descricao   VARCHAR(1000),
    arquivo_id  VARCHAR(36),
    url         VARCHAR(1000),
    ordem       INT           NOT NULL DEFAULT 0
);

CREATE TABLE usuario (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome              VARCHAR(160)  NOT NULL,
    email             VARCHAR(200)  NOT NULL UNIQUE,
    senha_hash        VARCHAR(200)  NOT NULL,
    data_nascimento   DATE,
    senha_provisoria  BOOLEAN       NOT NULL DEFAULT TRUE,
    papel             VARCHAR(20)   NOT NULL DEFAULT 'ALUNO',
    ativo             BOOLEAN       NOT NULL DEFAULT TRUE,
    origem            VARCHAR(20)   NOT NULL DEFAULT 'MANUAL',
    criado_em         TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Matrícula: quais cursos estão liberados para cada usuário.
CREATE TABLE matricula (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT        NOT NULL REFERENCES usuario (id) ON DELETE CASCADE,
    curso_id    BIGINT        NOT NULL REFERENCES curso (id) ON DELETE CASCADE,
    ativa       BOOLEAN       NOT NULL DEFAULT TRUE,
    origem      VARCHAR(20)   NOT NULL DEFAULT 'MANUAL',
    criada_em   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_matricula UNIQUE (usuario_id, curso_id)
);

-- Compras recebidas pelo webhook da Eduzz (evita processar a mesma venda duas vezes).
CREATE TABLE compra (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id    BIGINT        NOT NULL REFERENCES usuario (id) ON DELETE CASCADE,
    curso_id      BIGINT        REFERENCES curso (id) ON DELETE SET NULL,
    transacao     VARCHAR(100)  NOT NULL UNIQUE,
    status        VARCHAR(60)   NOT NULL,
    atualizada_em TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_modulo_curso ON modulo (curso_id);
CREATE INDEX idx_topico_modulo ON topico (modulo_id);
CREATE INDEX idx_video_topico ON video (topico_id);
CREATE INDEX idx_matricula_usuario ON matricula (usuario_id);
